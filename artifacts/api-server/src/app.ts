import express, { type Express } from "express";
import cors from "cors";
import pinoHttp from "pino-http";
import router from "./routes";
import { logger } from "./lib/logger";

const app: Express = express();

app.use(
  pinoHttp({
    logger,
    serializers: {
      req(req) {
        return {
          id: req.id,
          method: req.method,
          url: req.url?.split("?")[0],
        };
      },
      res(res) {
        return {
          statusCode: res.statusCode,
        };
      },
    },
  }),
);
app.use(cors());
app.use(express.json());
app.use(express.urlencoded({ extended: true }));

// Primary API route
app.use("/api", router);
// Mirror path for app.liquihood.xyz via Cloudflare Transform Rule:
// CF rewrites /api/* → /liquihood-app/api/* before it reaches the server
app.use("/liquihood-app/api", router);

export default app;
